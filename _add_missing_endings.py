def item(
    rule_id: str,
    n: int,
    *,
    kind: str = "ending",
    grades: list[int],
    instruction: str,
    prompt: str,
    options: list[str],
    answer: str,
    feedback: str,
    prefix: str | None = None,
) -> dict:
    d: dict = {
        "id": f"drill-{rule_id}-{n:03d}",
        "kind": kind,
        "grades": grades,
        "ruleId": rule_id,
        "instruction": instruction,
        "prompt": prompt,
        "options": options,
        "answer": answer,
        "feedback": feedback,
    }
    if prefix is not None:
        d["prefix"] = prefix
    assert answer in options, (rule_id, n, answer, options)
    return d


def pack(
    rule_id: str,
    instruction: str,
    feedback: str,
    grades: list[int],
    rows: list[tuple],
) -> list[dict]:
    out = []
    for i, row in enumerate(rows, 1):
        prompt, options, answer = row[0], row[1], row[2]
        prefix = row[3] if len(row) > 3 else None
        out.append(
            item(
                rule_id,
                i,
                grades=grades,
                instruction=instruction,
                prompt=prompt,
                options=options,
                answer=answer,
                feedback=feedback,
                prefix=prefix,
            )
        )
    return out


