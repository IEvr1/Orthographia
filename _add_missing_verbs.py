def deaccent(s: str) -> str:
    return s.lower().translate(str.maketrans("άέήίόύώϊΐϋΰ", "αεηιουωιιυυ"))


def main() -> None:
    words_data = json.loads(WORDS_JSON.read_text(encoding="utf-8"))
    existing = {deaccent(w["word"]) for w in words_data["words"]}

    # Filter already present
    to_add = []
    skipped = []
    for word, grade, diff, hint in VERBS:
        if deaccent(word) in existing:
            skipped.append(word)
            continue
        if "___" not in hint:
            raise SystemExit(f"hint missing ___ for {word}")
        # leak check: word letters shouldn't appear as full token in hint
        if word.lower() in hint.lower():
            raise SystemExit(f"hint leaks word for {word}: {hint}")
        to_add.append(
            {
                "word": word,
                "grade": grade,
                "pos": "verb",
                "hint": hint,
                "definition": "",
                "family": "",
                "synonyms": "",
                "source": "mathima-orthografias-verbs",
                "difficulty": diff,
            }
        )

    # Append to mathima_g{N}.csv
    by_grade: dict[int, list[dict]] = {}
    for row in to_add:
        by_grade.setdefault(row["grade"], []).append(row)

    fieldnames = [
        "word",
        "grade",
        "pos",
        "hint",
        "definition",
        "family",
        "synonyms",
        "source",
        "difficulty",
    ]
    for grade, rows in sorted(by_grade.items()):
        path = LEXIKA / f"mathima_g{grade}.csv"
        existing_rows = []
        if path.exists():
            with path.open(encoding="utf-8-sig", newline="") as f:
                existing_rows = list(csv.DictReader(f))
        existing_keys = {deaccent(r["word"]) for r in existing_rows if r.get("word")}
        new_rows = [r for r in rows if deaccent(r["word"]) not in existing_keys]
        with path.open("w", encoding="utf-8", newline="") as f:
            w = csv.DictWriter(f, fieldnames=fieldnames)
            w.writeheader()
            for r in existing_rows:
                w.writerow({k: r.get(k, "") for k in fieldnames})
            for r in new_rows:
                w.writerow({k: r[k] for k in fieldnames})
        print(f"mathima_g{grade}.csv: +{len(new_rows)} verbs (file now {len(existing_rows)+len(new_rows)} rows)")

    OUT_JSON.write_text(
        json.dumps(
            {
                "added": to_add,
                "skipped_already_in_app": skipped,
                "counts_by_grade": {str(g): len(v) for g, v in by_grade.items()},
            },
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )
    print(f"To add: {len(to_add)} · skipped (already in app): {len(skipped)}")
    print(f"Wrote {OUT_JSON}")


if __name__ == "__main__":
    main()
