def js_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def clean_grade(grade: int) -> list[dict]:
    path = LEXIKA / f"grade{grade}.csv"
    with path.open(encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f))
    fieldnames = list(rows[0].keys())

    cleaned: list[dict] = []
    seen: set[str] = set()
    dropped = 0

    for r in rows:
        raw = (r.get("word") or "").strip()
        if not raw or raw in DROP:
            dropped += 1
            continue
        word = FIX.get(raw, raw)
        if word in DROP or word in DROP_AFTER:
            dropped += 1
            continue
        # Prefer curated; otherwise drop if OCR-looking
        if word not in CURATED:
            # keep only if looks like clean Greek (no OCR residue patterns)
            if re.search(r"[ίς]$", word) and word.endswith("ίς"):
                dropped += 1
                continue
            if any(x in word for x in ("ιι", "ίι", "αιη", "ιηλ", "ιυμ")):
                dropped += 1
                continue
            # no curated = drop for quality
            dropped += 1
            continue

        sent, expl, pos = CURATED[word]
        if word in seen:
            dropped += 1
            continue
        seen.add(word)
        cleaned.append(
            {
                "word": word,
                "grade": str(grade),
                "pos": pos,
                "hint": sent,
                "definition": expl,
                "family": (r.get("family") or "").strip(),
                "synonyms": (r.get("synonyms") or "").strip(),
                "source": "a_b_c_lexiko",
                "difficulty": str(r.get("difficulty") or 2),
            }
        )

    # Also add curated words for this grade that might be missing if we want density?
    # No — only keep from source list after fix.

    cleaned.sort(key=lambda x: x["word"].casefold())
    with path.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        w.writeheader()
        w.writerows(cleaned)
    print(f"grade{grade}: {len(rows)} → {len(cleaned)} (dropped {dropped})")
    return cleaned


def rebuild_canvas(rows2: list[dict], rows3: list[dict]) -> None:
    all_rows = rows2 + rows3
    total = len(all_rows)
    n2, n3 = len(rows2), len(rows3)
    with_sent = sum(1 for r in all_rows if r.get("hint"))
    with_expl = sum(1 for r in all_rows if r.get("definition"))
    pos_c = Counter(r["pos"] for r in all_rows)
    pos_labels, pos_counts = [], []
    for k, lab in [("noun", "ουσιαστικό"), ("verb", "ρήμα"), ("adj", "επίθετο")]:
        if pos_c.get(k):
            pos_labels.append(lab)
            pos_counts.append(pos_c[k])

    words_block = "\n".join(
        "{word:"
        + js_str(r["word"])
        + ",grade:"
        + r["grade"]
        + ",pos:"
        + js_str(r["pos"])
        + ",diff:"
        + str(int(r.get("difficulty") or 2))
        + ",sent:"
        + js_str(r.get("hint") or "")
        + ",expl:"
        + js_str(r.get("definition") or "")
        + ",fam:"
        + js_str((r.get("family") or "")[:40])
        + "},"
        for r in all_rows
    )

    # Reuse UI shell from existing abc canvas but replace data + PAGE=80 + default Β΄
    shell = (CANVAS / "lexikon-abc-bg.canvas.tsx").read_text(encoding="utf-8")
    header = shell.split("const WORDS: WordRow[] = [")[0]
    ui = shell.split("export default function LexikonWords()")[1]
    ui = "export default function LexikonAbcBg()" + ui
    ui = ui.replace("360 λέξεις", f"{total} λέξεις")
    ui = re.sub(r'value="\d+" label="Λέξεις"', f'value="{total}" label="Λέξεις"', ui)
    ui = re.sub(r'value="\d+" label="Με πρόταση"', f'value="{with_sent}" label="Με πρόταση"', ui)
    ui = re.sub(r'value="\d+" label="Με ορισμό"', f'value="{with_expl}" label="Με ορισμό"', ui)
    ui = ui.replace("n = 360", f"n = {total}")
    ui = ui.replace(
        "HelFont/OCR θόρυβος στο ΑΒΓ\n          φαίνεται σε ορισμένες λέξεις — διέγραψέ τες εδώ.",
        "Καθαρισμένο από HelFont/OCR · προτάσεις ξαναγραμμένες · 80/σελίδα.",
    )
    ui = ui.replace(
        "360 λέξεις από «Το Πρώτο μου Λεξικό» (Α΄–Γ΄ πηγή· ανακατανεμημένες σε Β΄ και Γ΄). Πρόταση cloze + ορισμός όπου υπάρχει.",
        f"{total} λέξεις από a_b_c_lexiko.pdf (Β΄ {n2} · Γ΄ {n3}). Ορθογραφία και προτάσεις καθαρισμένες.",
    )

    mid = f"""const WORDS: WordRow[] = [
{words_block}
];

const GRADE_LABELS = ["Β΄", "Γ΄"];
const GRADE_COUNTS = [{n2}, {n3}];
const POS_LABELS = {json.dumps(pos_labels, ensure_ascii=False)};
const POS_COUNTS = {pos_counts};
const DIFF_LABELS = ["1", "2", "3"];
const DIFF_COUNTS = [0, {total}, 0];

"""
    helpers = shell.split("const FILTERS = ")[1]
    helpers = "const FILTERS = " + helpers
    helpers = helpers.split("export default function")[0]
    helpers = helpers.replace("const PAGE_SIZE = 25;", "const PAGE_SIZE = 80;")
    # default filter Β΄ for clearer review
    ui = ui.replace(
        'useCanvasState<string>("filter", "Όλα")',
        'useCanvasState<string>("filter", "Β΄")',
    )
    # family card text
    with_fam = sum(1 for r in all_rows if (r.get("family") or "").strip())
    ui = re.sub(
        r"\d+ από \d+ λέξεις έχουν οικογένεια στο λεξικό\.",
        f"{with_fam} από {total} λέξεις έχουν οικογένεια στο λεξικό.",
        ui,
    )

    out = header + mid + helpers + ui
    out = out.replace("\r\n", "\n")
    OUT.write_text(out, encoding="utf-8", newline="\n")
    kb = OUT.stat().st_size / 1024
    print(f"wrote {OUT.name}: {total} words, {kb:.1f} KB")


