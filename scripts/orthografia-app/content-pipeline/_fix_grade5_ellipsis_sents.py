def ends_ellipsis(s: str) -> bool:
    s = (s or "").rstrip()
    return s.endswith("…") or s.endswith("...")


def main() -> None:
    missing = []
    for w in FIX:
        sent = FIX[w]
        # Prefer headword appearing in sentence (casefold); allow proper-noun casing.
        if w.casefold() not in sent.casefold() and w.lower() not in sent.lower():
            # special: Ακτύπης forms, μετάφρ ~ μετάφραση
            if w in ("ακτύπη", "μετάφρ"):
                continue
            missing.append(w)
    if missing:
        raise SystemExit(f"sentence missing headword: {missing}")

    text = CANVAS.read_text(encoding="utf-8")
    m = re.search(r"(const WORDS: WordRow\[\] = \[)(.*?)(\];)", text, re.S)
    if not m:
        raise SystemExit("WORDS not found")

    def repl_obj(mo: re.Match) -> str:
        obj = mo.group(0)
        wm = re.search(r'word:("(?:\\.|[^"\\])*")', obj)
        sm = re.search(r'sent:("(?:\\.|[^"\\])*")', obj)
        if not wm or not sm:
            return obj
        word = json.loads(wm.group(1))
        sent = json.loads(sm.group(1))
        if word in FIX and ends_ellipsis(sent):
            new = json.dumps(FIX[word], ensure_ascii=False)
            return obj[: sm.start(1)] + new + obj[sm.end(1) :]
        if ends_ellipsis(sent) and word not in FIX:
            raise SystemExit(f"no fix for {word!r}: {sent!r}")
        return obj

    body = re.sub(r"\{[^{}]+\}", repl_obj, m.group(2))
    CANVAS.write_text(text[: m.start(2)] + body + text[m.end(2) :], encoding="utf-8")

    data = json.loads(ANALYSIS.read_text(encoding="utf-8"))
    n_json = 0
    for w in data["words"]:
        if w["word"] in FIX:
            w["sent"] = FIX[w["word"]]
            n_json += 1

    ANALYSIS.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    # verify canvas
    t2 = CANVAS.read_text(encoding="utf-8")
    left = []
    for o in re.findall(
        r"\{[^{}]+\}",
        re.search(r"const WORDS: WordRow\[\] = \[(.*?)\];", t2, re.S).group(1),
    ):
        sm = re.search(r'sent:("(?:\\.|[^"\\])*")', o)
        wm = re.search(r'word:("(?:\\.|[^"\\])*")', o)
        if not sm or not wm:
            continue
        s = json.loads(sm.group(1))
        if ends_ellipsis(s):
            left.append(json.loads(wm.group(1)))

    print("canvas bytes", CANVAS.stat().st_size)
    print("analysis synced", n_json)
    print("remaining ellipsis", len(left), left[:10])


if __name__ == "__main__":
    main()
