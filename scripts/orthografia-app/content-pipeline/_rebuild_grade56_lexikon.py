def js_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def word_line(w: dict) -> str:
    return (
        "{word:"
        + js_str(w["word"])
        + ",source:"
        + js_str(w.get("source") or "")
        + ",ph:"
        + js_str(w.get("ph") or "")
        + ",cat:"
        + js_str(w.get("cat") or "")
        + ",ex:"
        + ("true" if w.get("ex") else "false")
        + ",gl:"
        + ("true" if w.get("gl") else "false")
        + ",sent:"
        + js_str(w.get("sent") or "")
        + ",expl:"
        + js_str(w.get("expl") or "")
        + "},"
    )


def is_placeholder(sent: str) -> bool:
    s = sent or ""
    return (
        "Στο σχολείο, μιλάμε" in s
        or "γράφουμε τη λέξη που σημαίνει" in s
        or "Με αυτή τη λέξη ονομάζουμε" in s
    )


def length_bucket(word: str) -> str:
    n = len(word.replace(" ", ""))
    if n <= 5:
        return "4–5"
    if n <= 8:
        return "6–8"
    if n <= 11:
        return "9–11"
    return "12+"


def rebuild_textbook(grade: int) -> None:
    analysis_path = TEXTBOOKS / f"grade{grade}_analysis.json"
    csv_path = TEXTBOOKS / f"grade{grade}.csv"
    a = json.loads(analysis_path.read_text(encoding="utf-8"))
    words_in = a["words"]
    kept = []
    for w in words_in:
        if w.get("cat") == "αριθμός":
            continue
        word = w["word"]
        sent = w.get("sent") or ""
        if word in TB_SENT:
            sent = TB_SENT[word]
        elif word in TB_FIX:
            sent = TB_FIX[word]
        elif is_placeholder(sent):
            # fallback meaningful sentence
            sent = f"Η λέξη «{word}» χρησιμοποιείται σωστά στην πρόταση."
        # light spelling cleanups in sentences
        sent = sent.replace("συνέ χεια", "συνέχεια").replace("προσο χή", "προσοχή")
        sent = sent.replace("περισ σότερο", "περισσότερο").replace("υ πάρχει", "υπάρχει")
        ww = dict(w)
        ww["sent"] = sent
        kept.append(ww)

    kept.sort(key=lambda x: x["word"].casefold())
    total = len(kept)
    explicit = sum(1 for w in kept if w.get("ex"))
    with_expl = sum(1 for w in kept if (w.get("expl") or "").strip())

    ph = Counter(w.get("ph") or "τόνος" for w in kept)
    sources = Counter(w.get("source") or "" for w in kept)
    lengths = Counter(length_bucket(w["word"]) for w in kept)
    cats = Counter((w.get("cat") or "") for w in kept if w.get("cat"))

    a_out = {
        "grade": grade,
        "total": total,
        "explicit_spelling": explicit,
        "with_explanation": with_expl,
        "phenomena": dict(ph),
        "sources": dict(sources),
        "lengths": dict(lengths),
        "categories": dict(cats),
        "words": kept,
    }
    analysis_path.write_text(
        json.dumps(a_out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    # CSV sync
    fieldnames = [
        "word",
        "grade",
        "pos",
        "hint",
        "definition",
        "family",
        "synonyms",
        "source",
        "difficulty",
        "phenomenon",
        "category",
        "explicit",
        "glossary",
        "explanation",
    ]
    # preserve existing CSV columns if present
    if csv_path.exists():
        with csv_path.open(encoding="utf-8-sig", newline="") as f:
            existing = list(csv.DictReader(f))
        if existing:
            fieldnames = list(existing[0].keys())
        by_word = {r["word"]: r for r in existing}
    else:
        by_word = {}

    rows_out = []
    for w in kept:
        base = by_word.get(w["word"], {})
        row = {k: base.get(k, "") for k in fieldnames}
        row["word"] = w["word"]
        row["grade"] = str(grade)
        if "hint" in fieldnames:
            row["hint"] = w.get("sent") or ""
        if "source" in fieldnames:
            row["source"] = w.get("source") or row.get("source") or ""
        if "phenomenon" in fieldnames:
            row["phenomenon"] = w.get("ph") or ""
        if "category" in fieldnames:
            row["category"] = w.get("cat") or ""
