def clean_lexikon_csv(grade: int) -> list[dict]:
    path = LEXIKA / f"grade{grade}.csv"
    with path.open(encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f))
    fieldnames = list(rows[0].keys()) if rows else [
        "word",
        "grade",
        "pos",
        "hint",
        "definition",
        "family",
        "synonyms",
        "source",
        "difficulty",
    ]

    cleaned = []
    for r in rows:
        word = (r.get("word") or "").strip()
        # normalize common OCR
        if word == "γράµµα":
            word = "γράμμα"
            r["word"] = word
        if word in LEX_DROP:
            continue
        if len(word) < 3:
            continue
        # fix from curated
        if word in LEX_SENT:
            sent, expl = LEX_SENT[word]
            r["hint"] = sent
            r["definition"] = expl
        else:
            # complete incomplete blanks where possible
            hint = (r.get("hint") or "").strip()
            definition = (r.get("definition") or "").strip()
            if "___" in hint:
                # try fill with word if hint is almost a full sentence
                filled = hint.replace("___", word)
                if filled.endswith(word) or word in filled:
                    # better: craft simple sentence
                    r["hint"] = f"Η λέξη «{word}» εμφανίζεται συχνά στα κείμενα της τάξης."
                else:
                    r["hint"] = filled
            elif not hint and definition and not definition.startswith("("):
                # use short definition as expl only; invent sentence
                r["hint"] = f"Μάθαμε τη σημασία της λέξης «{word}»."
            # clean spacing in definition
            if definition:
                definition = re.sub(r"\s+", " ", definition)
                definition = definition.replace("εξου σία", "εξουσία")
                definition = definition.replace("γέ λια", "γέλια")
                definition = definition.replace("εμ βαδόν", "εμβαδόν")
                r["definition"] = definition
        r["grade"] = str(grade)
        cleaned.append(r)

    # dedupe by word keeping first
    seen = set()
    uniq = []
    for r in cleaned:
        w = r["word"]
        if w in seen:
            continue
        seen.add(w)
        uniq.append(r)

    uniq.sort(key=lambda r: r["word"].casefold())
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(uniq)
    print(f"lexika grade{grade}: {len(rows)} → {len(uniq)}")
    return uniq


def lex_word_line(r: dict) -> str:
    return (
        "{word:"
        + js_str(r["word"])
        + ",grade:"
        + str(int(r.get("grade") or 0))
        + ",pos:"
        + js_str(r.get("pos") or "noun")
        + ",diff:"
        + str(int(r.get("difficulty") or 3))
        + ",sent:"
        + js_str(r.get("hint") or "")
        + ",expl:"
        + js_str(r.get("definition") or "")
        + ",fam:"
        + js_str((r.get("family") or "")[:80])
        + "},"
    )


