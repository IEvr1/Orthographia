    diff_c = Counter(int(r.get("difficulty") or 3) for r in rows)

    pos_labels = []
    pos_counts = []
    for key, label in [("noun", "ουσιαστικό"), ("verb", "ρήμα"), ("adj", "επίθετο")]:
        if pos_c.get(key):
            pos_labels.append(label)
            pos_counts.append(pos_c[key])

