def main() -> None:
    leaks: list[str] = []
    for word, entry in CURATED_HINTS.items():
        root = guess_morphemes(word).get("root")
        if hint_leaks_word(entry["hint"], word, root):
            leaks.append(word)

    if leaks:
        print("Hints that leak target word/root:", ", ".join(leaks), file=sys.stderr)
        raise SystemExit(1)

    payload = {"version": 1, "overrides": CURATED_HINTS}
    OVERRIDES_FILE.parent.mkdir(parents=True, exist_ok=True)
    OVERRIDES_FILE.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Wrote {len(CURATED_HINTS)} overrides -> {OVERRIDES_FILE}")


if __name__ == "__main__":
    main()
